// Moves the five sites to another set of origins, for example from localhost to the HTTPS
// origins they are deployed on.
//
//   node scripts/set-origins.mjs <profile> [--dry-run]
//
// Each site names its partners by full network URL (in its .hocon), lists their origins
// in allowed_peers (in its manifest), and lists the origins allowed to call its shared
// actions (in its bridge). This script rewrites all of those consistently from the
// profile in reliefmesh.origins.json, then re-runs the official build, rewrites the
// hosting header files and re-signs the TrustRegistry attestations (they bind each
// network's URL and the digest of its published definition).
//
// It edits source files only. Generated files are regenerated, never patched.
import { spawnSync } from "node:child_process";
import { readdir, readFile, stat, writeFile } from "node:fs/promises";
import path from "node:path";
import { abs, SITES } from "./lib/sites.mjs";

const args = process.argv.slice(2);
const dryRun = args.includes("--dry-run");
const target = args.find((arg) => !arg.startsWith("--"));
const LOOPBACK = ["localhost", "127.0.0.1", "[::1]"];

const doc = JSON.parse(await readFile(abs("reliefmesh.origins.json"), "utf8"));
if (!target || !doc.profiles[target]) {
  console.error(`Usage: node scripts/set-origins.mjs <profile> [--dry-run]\nProfiles: ${Object.keys(doc.profiles).join(", ")}\nActive:   ${doc.active}`);
  process.exit(2);
}

const from = doc.profiles[doc.active];
const to = doc.profiles[target];
const keys = [...SITES.map((site) => site.id), "inspector"];

// ---- validate the target profile -----------------------------------------------------
const problems = [];
const seen = new Map();
for (const key of keys) {
  const value = to[key];
  if (key === "inspector" && !value) continue;
  if (!value) { problems.push(`${target}.${key} is missing.`); continue; }
  let url;
  try { url = new URL(value); } catch { problems.push(`${target}.${key} is not a URL: ${value}`); continue; }
  if (url.origin !== value) problems.push(`${target}.${key} must be an origin only (scheme, host, port), with no path: ${value}`);
  if (url.protocol !== "https:" && !LOOPBACK.includes(url.hostname)) problems.push(`${target}.${key} must use https: ${value}`);
  if (/\.example$/.test(url.hostname)) problems.push(`${target}.${key} is still the placeholder ${value}. Put the real origin in reliefmesh.origins.json first.`);
  if (seen.has(value)) problems.push(`${target}.${key} and ${target}.${seen.get(value)} are the same origin. Each site needs its own origin: the runtime's consent and the browser's isolation are per origin.`);
  seen.set(value, key);
}
if (problems.length) {
  for (const problem of problems) console.error(`ERROR: ${problem}`);
  process.exit(1);
}

// ---- rewrite -----------------------------------------------------------------------
const pairs = keys
  .filter((key) => from[key] && to[key] && from[key] !== to[key])
  .map((key) => [from[key], to[key]])
  .sort((a, b) => b[0].length - a[0].length);
const escape = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
// An origin must not match inside a longer one, such as :8080 inside :80801.
const pattern = pairs.length ? new RegExp(pairs.map(([old]) => `${escape(old)}(?![0-9A-Za-z.-])`).join("|"), "g") : null;
const replacement = new Map(pairs);

const SOURCE_FILES = /(\.hocon|agent-manifest\.json|partners\.json|site-links\.js|command-data\.js)$/;
const SKIP_DIRS = new Set(["runtime", "node_modules", "dist", "tests", ".well-known", "assets"]);

async function sourceFiles(dir) {
  const out = [];
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) { if (!SKIP_DIRS.has(entry.name)) out.push(...await sourceFiles(full)); continue; }
    // The bridge's own manifest is generated by the official build.
    if (SOURCE_FILES.test(entry.name) && !(entry.name === "agent-manifest.json" && path.basename(dir) === "bridge")) out.push(full);
  }
  return out;
}

let changedFiles = 0;
if (pattern) {
  for (const site of SITES) {
    for (const file of await sourceFiles(abs(site.root))) {
      const before = await readFile(file, "utf8");
      const after = before.replace(pattern, (match) => replacement.get(match));
      if (after === before) continue;
      changedFiles += 1;
      const count = (before.match(pattern) || []).length;
      console.log(`${dryRun ? "would rewrite" : "rewrote"} ${path.relative(abs(), file)} (${count} origin reference${count === 1 ? "" : "s"})`);
      if (!dryRun) await writeFile(file, after);
    }
  }
}
console.log(`${doc.active} -> ${target}: ${changedFiles} file(s)${dryRun ? " would change" : " changed"}.`);
if (dryRun) process.exit(0);

doc.active = target;
await writeFile(abs("reliefmesh.origins.json"), `${JSON.stringify(doc, null, 2)}\n`);

// ---- regenerate everything that depends on the origins ---------------------------------
const run = (label, script, extra = []) => {
  console.log(`\n--- ${label} ---`);
  const result = spawnSync(process.execPath, [abs("scripts", script), ...extra], { stdio: "inherit" });
  if (result.status !== 0) { console.error(`${label} failed.`); process.exit(1); }
};
run("Official build of every network", "build-networks.mjs");
run("Hosting header files", "write-hosting-config.mjs");
run("Re-sign TrustRegistry attestations", "sign-trust.mjs", ["--force"]);

const built = await stat(abs("sites/command/dist")).then(() => true, () => false);
console.log(`\nDone. The published files now name the "${target}" origins.`);
console.log("Next:");
console.log("  npm --prefix sites/command run build     rebuild Command, so dist/ carries the new files");
if (!built) console.log("  (sites/command/dist does not exist yet)");
console.log("  npm run networks:check                   confirm every site passes the official check");
console.log("  npm run check:partners                   with the sites served or deployed, check each call path");
