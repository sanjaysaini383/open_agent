// Writes the static-hosting header files for every site, from the list in the official
// skill's "Static hosting" section (references/bundle_and_hosting.md):
//
//   _headers      Netlify, Cloudflare Pages and compatible hosts
//   vercel.json   Vercel
//
// Only the public agent files get Access-Control-Allow-Origin: *. Business pages and the
// bridge do not. Nothing sets X-Frame-Options or frame-ancestors, because other agent
// sites load bridge/action-bridge.html in a hidden frame.
import { writeFile } from "node:fs/promises";
import { abs, SITES } from "./lib/sites.mjs";

const WORKER_CSP = "default-src 'none'; script-src blob:; connect-src 'none'; worker-src 'none'";

// Extra public, read-only files a site publishes for other origins.
const EXTRA_PUBLIC = {
  trustregistry: ["trust-keys.json", "attestations.json"],
  command: ["partners.json"],
};

for (const site of SITES) {
  const files = [
    "agent-manifest.json",
    `${site.network}.network.json`,
    "links.json",
    "agent-mcp.json",
    ".well-known/nsdeploy.json",
    ".well-known/nsdeploy-agent.json",
    ...(EXTRA_PUBLIC[site.id] || []),
  ];

  const headers = [
    "# Generated by scripts/write-hosting-config.mjs. Public agent files only get CORS.",
    ...files.flatMap((file) => [`/${file}`, "  Access-Control-Allow-Origin: *", "  Cache-Control: no-cache"]),
    "/runtime/sandbox-worker.js",
    `  Content-Security-Policy: ${WORKER_CSP}`,
    "/*",
    "  X-Content-Type-Options: nosniff",
    "  Referrer-Policy: strict-origin-when-cross-origin",
    "",
  ].join("\n");

  const vercel = {
    $schema: "https://openapi.vercel.sh/vercel.json",
    cleanUrls: false,
    trailingSlash: false,
    headers: [
      ...files.map((file) => ({
        source: `/${file}`,
        headers: [
          { key: "Access-Control-Allow-Origin", value: "*" },
          { key: "Cache-Control", value: "no-cache" },
        ],
      })),
      { source: "/runtime/sandbox-worker.js", headers: [{ key: "Content-Security-Policy", value: WORKER_CSP }] },
      {
        source: "/(.*)",
        headers: [
          { key: "X-Content-Type-Options", value: "nosniff" },
          { key: "Referrer-Policy", value: "strict-origin-when-cross-origin" },
        ],
      },
    ],
  };
  // Command is a single-page app: unknown paths fall back to index.html.
  if (site.id === "command") {
    vercel.rewrites = [{ source: "/((?!.*\\.).*)", destination: "/index.html" }];
  }

  await writeFile(abs(site.root, "_headers"), headers);
  await writeFile(abs(site.root, "vercel.json"), `${JSON.stringify(vercel, null, 2)}\n`);
  console.log(`Wrote ${site.root}/_headers and vercel.json`);
}
