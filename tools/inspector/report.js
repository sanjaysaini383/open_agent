// Turns an inspection report into something a person reads: Markdown or plain text.
// No DOM and no Node APIs, so the web app and the CLI share it.

export const STATUS_LABEL = { pass: "PASS", warn: "WARN", fail: "FAIL", info: "INFO", skip: "SKIP" };
export const GROUP_LABEL = {
  address: "Address", publication: "Public files and CORS", manifest: "Manifest", network: "Network definition", agents: "Agents and capabilities",
  runtime: "Runtime", actions: "Site actions and bridge", partners: "Partner networks", security: "Security", official: "Official checker (check_partner.mjs)",
};

const VERDICT = { compatible: "Interoperable", "compatible-with-warnings": "Interoperable, with warnings", "not-compatible": "Not interoperable yet" };
const cell = (value) => String(value ?? "").replace(/\|/g, "\\|").replace(/\r?\n/g, " ");

export function groups(report) {
  const order = Object.keys(GROUP_LABEL);
  const present = [...new Set(report.checks.map((check) => check.group))].sort((a, b) => order.indexOf(a) - order.indexOf(b));
  return present.map((group) => ({ group, label: GROUP_LABEL[group] || group, checks: report.checks.filter((check) => check.group === group) }));
}

export function toMarkdown(report) {
  const lines = [];
  lines.push(`# Agent interoperability report`, "", `**${VERDICT[report.summary.verdict]}** — ${report.summary.headline}`, "");
  lines.push("| | |", "| --- | --- |",
    `| Inspected | ${cell(report.input)} |`,
    `| Network URL | ${cell(report.networkUrl || "not resolved")} |`,
    `| Checked from | ${cell(report.checkedFrom)} (${report.mode === "browser" ? "a browser, with real CORS enforcement" : "Node, with CORS headers inspected"}) |`,
    `| When | ${report.generatedAt} |`,
    `| Against | ${report.specification} |`,
    `| Result | ${report.summary.pass} passed, ${report.summary.warn} warnings, ${report.summary.fail} failed, ${report.summary.info} notes${report.summary.skip ? `, ${report.summary.skip} skipped` : ""} |`, "");

  for (const { label, checks } of groups(report)) {
    lines.push(`## ${label}`, "", "| Result | Check | Detail |", "| --- | --- | --- |");
    for (const check of checks) lines.push(`| ${STATUS_LABEL[check.status]} | ${cell(check.title)} | ${cell(check.detail)}${check.fix ? ` **Fix:** ${cell(check.fix)}` : ""} |`);
    lines.push("");
  }

  if (report.network) {
    lines.push("## Agents", "", `Front agent: \`${report.network.frontAgent}\`. ${cell(report.network.description)}`, "", "| Agent | What it does | May call |", "| --- | --- | --- |");
    for (const agent of report.network.agents) lines.push(`| \`${agent.name}\`${agent.isFront ? " (front)" : ""} | ${cell(agent.description)} | ${cell(agent.tools.map((tool) => `${tool.ref} (${tool.kind})`).join(", ") || "—")} |`);
    lines.push("");
    if (report.network.sampleQueries.length) lines.push("Sample queries:", "", ...report.network.sampleQueries.map((query) => `- ${query}`), "");
  }
  if (report.actions) {
    lines.push(`## Actions shared with ${report.actions.sharedWith}`, "");
    if (report.actions.catalog.length) {
      lines.push("| Action | Effect | Description |", "| --- | --- | --- |");
      for (const action of report.actions.catalog) lines.push(`| \`${action.name}\` | ${action.effect} | ${cell(action.description)} |`);
    } else lines.push("None.");
    lines.push("");
  }
  if (report.callerAdds) {
    lines.push("## To call this network from your site", "", "```text",
      `allowed_peers in agent-manifest.json:  "${report.callerAdds.allowedPeers}"`,
      `tools of the calling agent:            "${report.callerAdds.tool}"`,
      `link_labels in the .hocon:             "${report.callerAdds.tool}": "${report.callerAdds.linkLabel}"`,
      `tool name the model sees:              ${report.callerAdds.toolName}`,
      "```", "");
  }
  lines.push("---", `Generated by the ${report.tool}. Parsing and validation use the official agentic-web browser runtime.`, "");
  return lines.join("\n");
}

export function toText(report) {
  const lines = [];
  lines.push(`${VERDICT[report.summary.verdict].toUpperCase()}: ${report.summary.headline}`);
  lines.push(`Inspected:    ${report.input}`);
  if (report.networkUrl) lines.push(`Network URL:  ${report.networkUrl}`);
  lines.push(`Checked from: ${report.checkedFrom} (${report.mode})`);
  lines.push("");
  for (const { label, checks } of groups(report)) {
    lines.push(label);
    for (const check of checks) {
      lines.push(`  [${STATUS_LABEL[check.status]}] ${check.title}`);
      lines.push(`         ${check.detail}`);
      if (check.fix) lines.push(`         Fix: ${check.fix}`);
    }
    lines.push("");
  }
  if (report.callerAdds) {
    lines.push("To call this network from your site:");
    lines.push(`  allowed_peers: "${report.callerAdds.allowedPeers}"`);
    lines.push(`  tools:         "${report.callerAdds.tool}"`);
    lines.push(`  link_labels:   "${report.callerAdds.tool}": "${report.callerAdds.linkLabel}"`);
    lines.push("");
  }
  lines.push(`${report.summary.pass} passed, ${report.summary.warn} warnings, ${report.summary.fail} failed, ${report.summary.info} notes${report.summary.skip ? `, ${report.summary.skip} skipped` : ""}.`);
  return lines.join("\n");
}
